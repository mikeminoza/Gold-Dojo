# 2011-2012 meetings with a Chairman's press briefing: statement at about 12:30 p.m. ET
FOMC_1230 = {"2011-04-27", "2011-06-22", "2011-11-02", "2012-01-25", "2012-04-25", "2012-06-20",
             "2012-09-13", "2012-12-12"}
FOMC_2PM_FROM = date(2013, 3, 20)  # first meeting after the 2013-03-13 announcement

# Unscheduled FOMC actions with a statement: listed for completeness, NOT traded (irregular times,
# one on a Sunday; their timing was not knowable in advance).
FOMC_UNSCHEDULED = ["2007-08-10", "2007-08-17", "2008-01-22", "2008-03-11", "2008-10-08", "2010-05-09",
                    "2020-03-03", "2020-03-15"]


def _days(block):
    return [date.fromisoformat(s) for s in block.split()]


def fomc_time(d):
    if d.isoformat() in FOMC_1230:
        return time(12, 30)
    return time(14, 0) if d >= FOMC_2PM_FROM else time(14, 15)


def events():
    rows = [(d, time(8, 30), "NFP") for d in _days(NFP)] + [(d, time(8, 30), "CPI") for d in _days(CPI)]
    rows += [(d, fomc_time(d), "FOMC") for d in _days(FOMC)]
    df = pd.DataFrame(rows, columns=["date", "time_et", "type"]).sort_values(["date", "time_et"])
    return df.reset_index(drop=True)


def validate(df):
    problems = []
    for t, g in df.groupby("type"):
        if g.date.duplicated().any():
            problems.append(f"{t}: duplicate dates")
        wk = g[g.date.map(lambda d: d.weekday() >= 5)]
        if len(wk):
            problems.append(f"{t}: weekend dates {list(wk.date)}")
    nfp = df[df.type == "NFP"].date
    odd = [d for d in nfp if d.weekday() != 4]
    # one release per reference month: count per calendar month of release
    per_month = df.groupby(["type", df.date.map(lambda d: (d.year, d.month))]).size()
    return problems, odd, per_month[per_month > 1]


def main():
    df = events()
    problems, odd, multi = validate(df)
    if problems:
        raise SystemExit("\n".join(problems))
    out = df.copy()
    out["date"] = out.date.map(date.isoformat)
    out["time_et"] = out.time_et.map(lambda t: t.strftime("%H:%M"))
    out.to_csv(CSV, index=False)
    print(f"wrote {CSV}: " + ", ".join(f"{t} {n}" for t, n in df.type.value_counts().sort_index().items()))
    print("NFP not on a Friday:", ", ".join(f"{d} ({d:%a})" for d in odd))
    print("months with 2 releases of one type:", list(multi.index))


if __name__ == "__main__":
    main()
